"""Export a trained Q-table for the web UI.

Writes web/data/qtable.js, which defines one global:  window.TTT_QTABLE = {...};
The HTML/CSS/JS files are never modified, so the page code stays clean and the
data is the only generated file.

Safety:
  * every key and value is validated here before it is written
  * the JSON is escaped so it can never close a <script> tag or break out
    of the JavaScript literal (<, >, &, U+2028, U+2029 are \\u-escaped)
  * the browser validates the data again (engine.validateData) before use
"""
from __future__ import annotations

import json
import math
from pathlib import Path

from .agents import QAgent
from .evaluate import optimal_move_accuracy

_ALLOWED_CELLS = {-1, 0, 1}
_JS_ESCAPES = {
    "<": "\\u003c",
    ">": "\\u003e",
    "&": "\\u0026",
    "\u2028": "\\u2028",
    "\u2029": "\\u2029",
}


def _check_row(key, row) -> None:
    if len(key) != 9 or any(c not in _ALLOWED_CELLS for c in key):
        raise ValueError(f"invalid board key in Q-table: {key!r}")
    if len(row) != 9 or not all(isinstance(v, (int, float)) and math.isfinite(v) for v in row):
        raise ValueError(f"invalid Q-values for board {key!r}")


def to_safe_js_json(obj) -> str:
    """JSON text that is also safe to embed inside a JavaScript/HTML file."""
    text = json.dumps(obj, separators=(",", ":"), allow_nan=False)
    for ch, esc in _JS_ESCAPES.items():
        text = text.replace(ch, esc)
    return text


def build_payload(agent: QAgent) -> dict:
    if not agent.use_symmetry:
        raise ValueError("The web UI expects a model trained with symmetry (the default).")
    table = {}
    for key, row in agent.Q.items():
        _check_row(key, row)
        table[",".join(str(int(c)) for c in key)] = [round(float(v), 4) for v in row]
    return {
        "meta": {
            "states": len(table),
            "gamma": float(agent.gamma),
            "accuracy": round(optimal_move_accuracy(agent), 4),
        },
        "Q": table,
    }


def export_web(model_path: str | Path, out_file: str | Path = "web/data/qtable.js") -> dict:
    agent = QAgent.load(model_path)
    payload = build_payload(agent)
    out_file = Path(out_file)
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(
        "// Generated by `python -m rl export` - do not edit by hand.\n"
        f"window.TTT_QTABLE = {to_safe_js_json(payload)};\n",
        encoding="utf-8",
    )
    return payload["meta"]